create table public.gallery_collections (
  gallery_key text primary key,
  title text not null,
  cms_enabled boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint gallery_collections_key_check
    check (gallery_key in ('interior', 'exterior'))
);

insert into public.gallery_collections (gallery_key, title)
values
  ('interior', 'Interior painting'),
  ('exterior', 'Exterior painting')
on conflict (gallery_key) do nothing;

create table public.gallery_images (
  id bigint generated by default as identity primary key,
  gallery_key text not null references public.gallery_collections(gallery_key) on delete cascade,
  storage_path text unique,
  image_url text,
  alt_text text not null,
  width integer,
  height integer,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint gallery_images_source_check
    check ((storage_path is not null) <> (image_url is not null)),
  constraint gallery_images_alt_text_check
    check (char_length(btrim(alt_text)) between 3 and 240),
  constraint gallery_images_sort_order_check check (sort_order >= 0),
  constraint gallery_images_width_check check (width is null or width > 0),
  constraint gallery_images_height_check check (height is null or height > 0)
);

create index gallery_images_gallery_order_idx
  on public.gallery_images (gallery_key, sort_order, id);

alter table public.gallery_collections enable row level security;
alter table public.gallery_images enable row level security;

create policy "Gallery collections are publicly readable"
  on public.gallery_collections
  for select
  to anon, authenticated
  using (true);

create policy "Gallery images are publicly readable"
  on public.gallery_images
  for select
  to anon, authenticated
  using (true);

revoke all on public.gallery_collections from anon, authenticated;
revoke all on public.gallery_images from anon, authenticated;
grant select on public.gallery_collections to anon, authenticated;
grant select on public.gallery_images to anon, authenticated;
grant all on public.gallery_collections to service_role;
grant all on public.gallery_images to service_role;
grant usage, select on sequence public.gallery_images_id_seq to service_role;

